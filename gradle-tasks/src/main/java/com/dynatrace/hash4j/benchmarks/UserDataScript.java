package com.dynatrace.hash4j.benchmarks;

final class UserDataScript {

    private static final String WORK_DIR = "/opt/jmh-benchmark-run";

    private UserDataScript() {}

    static String generate(
            BenchmarkConfig cfg,
            String s3Key,
            String id,
            String benchmarkArgs) {

        int hardKillMinutes = (int) Math.max(1, Math.ceil(cfg.maxRuntimeHours * 60)) + 30;
        String maxRuntimeForTimeout = formatTimeoutDuration(cfg.maxRuntimeHours);

        // %s placeholders are filled by the printf in bash; \\n produces a real newline
        // in the SNS message body. The fetch hint shows both shells because users on
        // Windows can't run `./gradlew`.
        String fetchHint = "Fetch with:\\n"
                + "  Linux/macOS: ./gradlew fetchResults -Ps3Key=\"%s\"\\n"
                + "  Windows:     .\\\\gradlew.bat fetchResults \"-Ps3Key=%s\"\\n";
        String snsBlock = """
                if [ "$EXIT" = "0" ]; then
                  SUBJECT="JMH complete: ${RUN_ID}"
                  MSG="$(printf 'Benchmark completed successfully.\\n\\nS3 prefix:\\n  s3://%s/%s\\n\\n""" + fetchHint + """
                ' "${BUCKET}" "${S3_KEY}" "${S3_KEY}" "${S3_KEY}")"
                elif [ "$EXIT" = "124" ]; then
                  SUBJECT="JMH TIMEOUT: ${RUN_ID}"
                  MSG="$(printf 'Benchmark exceeded max_runtime_hours=%s and was killed by timeout.\\nPartial results were uploaded.\\n\\nS3 prefix:\\n  s3://%s/%s\\n\\n""" + fetchHint + """
                ' "${MAX_RUNTIME_HOURS}" "${BUCKET}" "${S3_KEY}" "${S3_KEY}" "${S3_KEY}")"
                else
                  SUBJECT="JMH FAILED: ${RUN_ID} (exit=${EXIT})"
                  MSG="$(printf 'Benchmark exited with code %s. See jmh.log under the S3 prefix.\\n\\nS3 prefix:\\n  s3://%s/%s\\n\\n""" + fetchHint + """
                ' "${EXIT}" "${BUCKET}" "${S3_KEY}" "${S3_KEY}" "${S3_KEY}")"
                fi
                aws sns publish \\
                  --region "${REGION}" \\
                  --topic-arn "${SNS_TOPIC_ARN}" \\
                  --subject "${SUBJECT}" \\
                  --message "${MSG}" || true
                """;

        return """
                #!/bin/bash
                # Cloud-init user-data for hash4j benchmark run.
                # Generated by hash4j-benchmarks/gradle-tasks SubmitBenchmarksTask.
                set -uxeo pipefail

                # === Outer hard-kill watchdog =====================================
                # Belt-and-suspenders: even if cloud-init/apt/kernel hangs, the
                # instance terminates after max_runtime + 30 min grace.
                shutdown -h +%HARD_KILL_MINUTES% "hash4j-benchmarks outer watchdog" || true

                RUN_ID=%RUN_ID_QUOTED%
                BUCKET=%BUCKET_QUOTED%
                S3_KEY=%S3_KEY_QUOTED%
                REGION=%REGION_QUOTED%
                SNS_TOPIC_ARN=%SNS_TOPIC_ARN_QUOTED%
                MAX_RUNTIME_HOURS=%MAX_RUNTIME_HOURS_QUOTED%
                WORK_DIR=%WORK_DIR_QUOTED%

                mkdir -p "${WORK_DIR}/input" "${WORK_DIR}/output"
                touch "${WORK_DIR}/output/jmh.log"
                exec > "${WORK_DIR}/output/runner.log" 2>&1

                # Guarantee the instance terminates no matter how this script exits
                # (setup failure, signal, or normal completion). The outer +N shutdown
                # above is the fallback if the kernel is too wedged to fire this trap.
                trap 'shutdown -h now || true' EXIT

                START_TIME="$(date -u +%Y-%m-%dT%H:%M:%SZ)"
                START_EPOCH="$(date -u +%s)"

                # === Install packages ============================================
                apt-get update -q
                apt-get install -y -q %REMOTE_JAVA_PACKAGE% unzip curl jq

                # AWS CLI v2 from the official zip (apt's awscli on noble is v1).
                ARCH="$(uname -m)"
                case "${ARCH}" in
                  x86_64)  AWSCLI_URL="https://awscli.amazonaws.com/awscli-exe-linux-x86_64.zip"  ;;
                  aarch64) AWSCLI_URL="https://awscli.amazonaws.com/awscli-exe-linux-aarch64.zip" ;;
                  *) echo "Unsupported CPU architecture: ${ARCH}" >&2; exit 1 ;;
                esac
                curl -fsSL -o /tmp/awscliv2.zip "${AWSCLI_URL}"
                unzip -q /tmp/awscliv2.zip -d /tmp/
                /tmp/aws/install

                # === IMDSv2 token + instance metadata ============================
                IMDS_TOKEN="$(curl -sS -X PUT 'http://169.254.169.254/latest/api/token' \\
                    -H 'X-aws-ec2-metadata-token-ttl-seconds: 300')"
                imds() {
                  curl -sS -H "X-aws-ec2-metadata-token: ${IMDS_TOKEN}" \\
                    "http://169.254.169.254/latest/meta-data/$1"
                }
                INSTANCE_ID="$(imds instance-id)"
                INSTANCE_TYPE_RUNTIME="$(imds instance-type)"
                AMI_ID_RUNTIME="$(imds ami-id)"
                AZ="$(imds placement/availability-zone)"

                # === Pull inputs from S3 =========================================
                aws s3 sync "s3://${BUCKET}/${S3_KEY}input/" "${WORK_DIR}/input/"
                chmod +x "${WORK_DIR}/input/monitor.sh" || true

                # === Disable CPU turbo for benchmark reproducibility =============
                # Intel CPUs with the intel_pstate driver:
                TURBO_DISABLED="false"
                if [ -w /sys/devices/system/cpu/intel_pstate/no_turbo ]; then
                  echo 1 > /sys/devices/system/cpu/intel_pstate/no_turbo && TURBO_DISABLED="intel_pstate"
                fi
                # AMD / generic cpufreq driver:
                if [ -w /sys/devices/system/cpu/cpufreq/boost ]; then
                  echo 0 > /sys/devices/system/cpu/cpufreq/boost && TURBO_DISABLED="cpufreq"
                fi

                # === Run JMH with inner timeout watchdog =========================
                # From here on, allow failures so we always reach the SNS notification
                # and the shutdown call at the end, even if JMH or the upload errors out.
                set +e
                cd "${WORK_DIR}/output"
                timeout %MAX_RUNTIME_FOR_TIMEOUT% \\
                  java -jar "${WORK_DIR}/input/jmh.jar" %BENCHMARK_ARGS% \\
                    -rf json -rff "${WORK_DIR}/output/jmh-results.json" \\
                    > "${WORK_DIR}/output/jmh.log" 2>&1
                EXIT=$?

                END_TIME="$(date -u +%Y-%m-%dT%H:%M:%SZ)"
                END_EPOCH="$(date -u +%s)"
                DURATION=$(( END_EPOCH - START_EPOCH ))

                # === Collect host / java metadata ================================
                OS_PRETTY="$(. /etc/os-release && printf '%s' "${PRETTY_NAME:-unknown}")"
                KERNEL="$(uname -r)"

                LSCPU_OUT="$(lscpu 2>/dev/null || true)"
                lscpu_field() {
                  printf '%s' "${LSCPU_OUT}" | awk -F: -v k="$1" '$1==k {sub(/^[ \\t]+/, "", $2); print $2; exit}'
                }
                CPU_MODEL="$(lscpu_field 'Model name')"
                CPU_CORES_PER_SOCKET="$(lscpu_field 'Core(s) per socket')"
                CPU_SOCKETS="$(lscpu_field 'Socket(s)')"
                CPU_THREADS="$(lscpu_field 'CPU(s)')"
                if [ -n "${CPU_CORES_PER_SOCKET:-}" ] && [ -n "${CPU_SOCKETS:-}" ]; then
                  CPU_CORES=$(( CPU_CORES_PER_SOCKET * CPU_SOCKETS ))
                else
                  CPU_CORES=0
                fi
                CPU_L1D="$(lscpu_field 'L1d cache')"
                CPU_L1I="$(lscpu_field 'L1i cache')"
                CPU_L2="$(lscpu_field 'L2 cache')"
                CPU_L3="$(lscpu_field 'L3 cache')"
                # ARM uses "Features", x86 uses "flags" — only one is present.
                CPU_FLAGS="$(awk -F: '/^(Features|flags)/ {sub(/^[ \\t]+/, "", $2); print $2; exit}' /proc/cpuinfo)"
                CPU_GOVERNOR="$(cat /sys/devices/system/cpu/cpu0/cpufreq/scaling_governor 2>/dev/null || echo unknown)"
                CPU_SCALING_DRIVER="$(cat /sys/devices/system/cpu/cpu0/cpufreq/scaling_driver 2>/dev/null || echo unknown)"

                # transparent_hugepage/enabled prints all modes with the active one in [brackets]
                THP_ENABLED="$(grep -oP '\\[\\K[^]]+' /sys/kernel/mm/transparent_hugepage/enabled 2>/dev/null || true)"
                : "${THP_ENABLED:=unknown}"

                # Capture every vulnerabilities/* file as a JSON map. jq handles quoting / newlines.
                MITIGATIONS_JSON='{}'
                if [ -d /sys/devices/system/cpu/vulnerabilities ]; then
                  MITIGATIONS_JSON="$(
                    for f in /sys/devices/system/cpu/vulnerabilities/*; do
                      [ -f "$f" ] || continue
                      jq -nR --arg k "$(basename "$f")" --rawfile v "$f" '{($k): ($v | rtrimstr("\\n"))}'
                    done | jq -cs 'add // {}'
                  )"
                fi

                MEM_KB="$(awk '/MemTotal/ {print $2}' /proc/meminfo)"
                MEM_MB=$(( MEM_KB / 1024 ))

                JAVA_PROPS="$(java -XshowSettings:properties -version 2>&1 || true)"
                JAVA_VERSION="$(printf '%s' "${JAVA_PROPS}" | awk -F'= ' '/java.version =/ {print $2; exit}')"
                JAVA_VENDOR="$(printf '%s' "${JAVA_PROPS}" | awk -F'= ' '/java.vendor =/ {print $2; exit}')"
                JAVA_VM_NAME="$(printf '%s' "${JAVA_PROPS}" | awk -F'= ' '/java.vm.name =/ {print $2; exit}')"
                JAVA_HOME_RUNTIME="$(printf '%s' "${JAVA_PROPS}" | awk -F'= ' '/java.home =/ {print $2; exit}')"

                # JMH version from the bundled core jar's maven properties.
                JMH_VERSION="$(unzip -p "${WORK_DIR}/input/jmh.jar" META-INF/maven/org.openjdk.jmh/jmh-core/pom.properties 2>/dev/null | awk -F= '/^version=/ {print $2; exit}' | tr -d '\\r')"
                : "${JMH_VERSION:=unknown}"

                # Effective JVM defaults for the runtime that will fork JMH workers.
                JVM_FLAGS_RAW="$(java -XX:+PrintFlagsFinal -version 2>/dev/null || true)"
                extract_jvm_flag() {
                  printf '%s' "${JVM_FLAGS_RAW}" | awk -v k="$1" '$2==k {print $4; exit}'
                }
                JVM_MAX_HEAP="$(extract_jvm_flag MaxHeapSize)"
                JVM_INITIAL_HEAP="$(extract_jvm_flag InitialHeapSize)"
                JVM_USE_G1GC="$(extract_jvm_flag UseG1GC)"
                JVM_USE_PARALLELGC="$(extract_jvm_flag UseParallelGC)"
                JVM_USE_ZGC="$(extract_jvm_flag UseZGC)"
                JVM_USE_SERIALGC="$(extract_jvm_flag UseSerialGC)"
                JVM_USE_COMPRESSED_OOPS="$(extract_jvm_flag UseCompressedOops)"
                JVM_USE_THP="$(extract_jvm_flag UseTransparentHugePages)"
                JVM_TIERED_COMPILATION="$(extract_jvm_flag TieredCompilation)"
                JVM_TIERED_STOP_AT_LEVEL="$(extract_jvm_flag TieredStopAtLevel)"
                # Substitute null for any flag the JDK does not expose.
                [ -z "${JVM_MAX_HEAP}" ] && JVM_MAX_HEAP=null
                [ -z "${JVM_INITIAL_HEAP}" ] && JVM_INITIAL_HEAP=null
                [ -z "${JVM_USE_G1GC}" ] && JVM_USE_G1GC=null
                [ -z "${JVM_USE_PARALLELGC}" ] && JVM_USE_PARALLELGC=null
                [ -z "${JVM_USE_ZGC}" ] && JVM_USE_ZGC=null
                [ -z "${JVM_USE_SERIALGC}" ] && JVM_USE_SERIALGC=null
                [ -z "${JVM_USE_COMPRESSED_OOPS}" ] && JVM_USE_COMPRESSED_OOPS=null
                [ -z "${JVM_USE_THP}" ] && JVM_USE_THP=null
                [ -z "${JVM_TIERED_COMPILATION}" ] && JVM_TIERED_COMPILATION=null
                [ -z "${JVM_TIERED_STOP_AT_LEVEL}" ] && JVM_TIERED_STOP_AT_LEVEL=null

                # === Write metadata.runtime.json ==================================
                cat > "${WORK_DIR}/output/metadata.runtime.json" <<EOF
                {
                  "run": {
                    "start_time": "${START_TIME}",
                    "end_time": "${END_TIME}",
                    "duration_s": ${DURATION},
                    "exit_code": ${EXIT}
                  },
                  "aws": {
                    "region": "${REGION}",
                    "instance_type": "${INSTANCE_TYPE_RUNTIME}",
                    "ami_id": "${AMI_ID_RUNTIME}",
                    "availability_zone": "${AZ}"
                  },
                  "host": {
                    "os": "${OS_PRETTY}",
                    "kernel": "${KERNEL}",
                    "cpu_model": "${CPU_MODEL}",
                    "cpu_cores": ${CPU_CORES:-0},
                    "cpu_threads": ${CPU_THREADS:-0},
                    "cpu_flags": "${CPU_FLAGS}",
                    "cpu_caches": {
                      "l1d": "${CPU_L1D}",
                      "l1i": "${CPU_L1I}",
                      "l2": "${CPU_L2}",
                      "l3": "${CPU_L3}"
                    },
                    "cpu_governor": "${CPU_GOVERNOR}",
                    "cpu_scaling_driver": "${CPU_SCALING_DRIVER}",
                    "memory_mb": ${MEM_MB},
                    "turbo_disabled": "${TURBO_DISABLED}",
                    "transparent_hugepages": "${THP_ENABLED}",
                    "mitigations": ${MITIGATIONS_JSON}
                  },
                  "java": {
                    "version": "${JAVA_VERSION}",
                    "vendor": "${JAVA_VENDOR}",
                    "vm_name": "${JAVA_VM_NAME}",
                    "java_home": "${JAVA_HOME_RUNTIME}",
                    "jvm_flags": {
                      "MaxHeapSize": ${JVM_MAX_HEAP},
                      "InitialHeapSize": ${JVM_INITIAL_HEAP},
                      "UseG1GC": ${JVM_USE_G1GC},
                      "UseParallelGC": ${JVM_USE_PARALLELGC},
                      "UseZGC": ${JVM_USE_ZGC},
                      "UseSerialGC": ${JVM_USE_SERIALGC},
                      "UseCompressedOops": ${JVM_USE_COMPRESSED_OOPS},
                      "UseTransparentHugePages": ${JVM_USE_THP},
                      "TieredCompilation": ${JVM_TIERED_COMPILATION},
                      "TieredStopAtLevel": ${JVM_TIERED_STOP_AT_LEVEL}
                    }
                  },
                  "jmh": {
                    "version": "${JMH_VERSION}"
                  }
                }
                EOF

                # Also stage the local metadata for upload (no edit needed).
                cp "${WORK_DIR}/input/metadata.local.json" "${WORK_DIR}/output/metadata.local.json" || true

                # === Upload outputs to S3 ========================================
                aws s3 sync "${WORK_DIR}/output/" "s3://${BUCKET}/${S3_KEY}output/"

                # === SNS notification ============================================
                %SNS_BLOCK%

                # === Cancel outer watchdog and shut down ==========================
                shutdown -c || true
                shutdown -h now
                """
                .replace("%HARD_KILL_MINUTES%", String.valueOf(hardKillMinutes))
                .replace("%RUN_ID_QUOTED%", shellSingleQuote(id))
                .replace("%BUCKET_QUOTED%", shellSingleQuote(cfg.bucket))
                .replace("%S3_KEY_QUOTED%", shellSingleQuote(s3Key))
                .replace("%REGION_QUOTED%", shellSingleQuote(cfg.region))
                .replace("%SNS_TOPIC_ARN_QUOTED%", shellSingleQuote(cfg.snsTopicArn))
                .replace("%MAX_RUNTIME_HOURS_QUOTED%", shellSingleQuote(String.valueOf(cfg.maxRuntimeHours)))
                .replace("%WORK_DIR_QUOTED%", shellSingleQuote(WORK_DIR))
                .replace("%REMOTE_JAVA_PACKAGE%", cfg.remoteJavaPackage)
                .replace("%MAX_RUNTIME_FOR_TIMEOUT%", maxRuntimeForTimeout)
                .replace("%BENCHMARK_ARGS%", benchmarkArgs == null ? "" : benchmarkArgs)
                .replace("%SNS_BLOCK%", snsBlock);
    }

    static String shellSingleQuote(String s) {
        return "'" + s.replace("'", "'\\''") + "'";
    }

    static String formatTimeoutDuration(double hours) {
        if (hours >= 1.0 && hours == Math.floor(hours)) {
            return ((long) hours) + "h";
        }
        long minutes = Math.max(1L, Math.round(hours * 60.0));
        return minutes + "m";
    }
}
